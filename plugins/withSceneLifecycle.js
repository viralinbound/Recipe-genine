/**
 * withSceneLifecycle
 *
 * iOS 27.1 traps at launch (UIKit `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`)
 * when an app doesn't adopt the UIScene life cycle. The Expo SDK 57 prebuild template still
 * generates an AppDelegate-only startup, so this plugin:
 *   1. adds UIApplicationSceneManifest to Info.plist (single scene, SceneDelegate),
 *   2. writes ios/<Project>/SceneDelegate.swift, a thin subclass of expo's ExpoAppSceneDelegate
 *      (expo >= 57.0.30), which creates the UIWindow for the UIWindowScene, starts React Native
 *      in it, and forwards URL / user-activity / life-cycle events (deep links: recipegenie://),
 *   3. patches AppDelegate.swift so it conforms to ExpoReactNativeFactoryProvider and no longer
 *      creates the window itself (it still creates the React Native factory).
 * Idempotent, so it survives `npx expo prebuild --clean`.
 */
const fs = require('fs');
const path = require('path');
const {
  withInfoPlist,
  withAppDelegate,
  withDangerousMod,
  withXcodeProject,
  IOSConfig,
} = require('expo/config-plugins');

const SCENE_DELEGATE_FILE = 'SceneDelegate.swift';

const SCENE_DELEGATE_SOURCE = `internal import Expo
import UIKit

/// Scene delegate required by iOS 27.1+ (UIScene life cycle).
/// ExpoAppSceneDelegate creates the UIWindow for the connecting UIWindowScene, starts React Native
/// with the factory owned by AppDelegate, and forwards openURL / continueUserActivity / life-cycle
/// events back to AppDelegate (and Expo's subscribers), so deep links keep working.
/// Generated by plugins/withSceneLifecycle.js; edit that plugin instead of this file.
class SceneDelegate: ExpoAppSceneDelegate {}
`;

function withSceneManifest(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });
}

function patchAppDelegate(src) {
  let out = src;
  // Conform to ExpoReactNativeFactoryProvider so ExpoAppSceneDelegate can reach the factory/window.
  if (!out.includes('ExpoReactNativeFactoryProvider')) {
    out = out.replace(
      /class AppDelegate:\s*ExpoAppDelegate\s*\{/,
      'class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {'
    );
  }
  // The window is now created by SceneDelegate; drop the AppDelegate-owned window + startReactNative.
  out = out.replace(
    /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\([\s\S]*?\)\s*\n#endif\n/,
    '    // UIScene life cycle (iOS 27.1+): SceneDelegate creates the window and starts React Native.\n'
  );
  if (!out.includes('ExpoReactNativeFactoryProvider') || out.includes('UIWindow(frame: UIScreen.main.bounds)')) {
    throw new Error(
      '[withSceneLifecycle] AppDelegate.swift did not match the expected Expo template; update the plugin.'
    );
  }
  return out;
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (cfg) => {
    if (cfg.modResults.language !== 'swift') {
      throw new Error('[withSceneLifecycle] Only Swift AppDelegates are supported.');
    }
    cfg.modResults.contents = patchAppDelegate(cfg.modResults.contents);
    return cfg;
  });
}

function withSceneDelegateFile(config) {
  config = withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
      const file = path.join(cfg.modRequest.platformProjectRoot, projectName, SCENE_DELEGATE_FILE);
      fs.writeFileSync(file, SCENE_DELEGATE_SOURCE);
      return cfg;
    },
  ]);
  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = `${projectName}/${SCENE_DELEGATE_FILE}`;
    if (!project.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project,
      });
    }
    return cfg;
  });
}

module.exports = function withSceneLifecycle(config) {
  config = withSceneManifest(config);
  config = withSceneAppDelegate(config);
  config = withSceneDelegateFile(config);
  return config;
};
